    // ── Private Helpers ──────────────────────────────────────────────────────────

    private void insertUser(Long userId, String username, String walletBalance) {
        jdbcTemplate.update(
                "INSERT INTO users (user_id, username, wallet_balance) VALUES (?, ?, ?)",
                userId, username, new BigDecimal(walletBalance));
    }

    private void insertPortfolio(Long id, Long userId, Long portfolioNumber, String name,
                                  String description, String currency,
                                  RiskLevel riskLevel, InvestmentGoal investmentGoal,
                                  BigDecimal targetValue, InvestmentHorizon investmentHorizon,
                                  LocalDateTime createdAt, LocalDateTime updatedAt) {
        jdbcTemplate.update(
                "INSERT INTO portfolios (id, user_id, portfolio_number, name, description, currency, " +
                "risk_level, investment_goal, target_value, investment_horizon, created_at, updated_at) " +
                "VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)",
                id, userId, portfolioNumber, name, description, currency,
                riskLevel != null ? riskLevel.name() : null,
                investmentGoal != null ? investmentGoal.name() : null,
                targetValue,
                investmentHorizon != null ? investmentHorizon.name() : null,
                Timestamp.valueOf(createdAt),
                updatedAt != null ? Timestamp.valueOf(updatedAt) : null);
    }

    private void insertPortfolioItem(Long portfolioId, AssetType assetType,
                                      String symbol, String name,
                                      String quantity, String purchasePrice,
                                      String currentPrice, LocalDateTime purchaseDate) {
        jdbcTemplate.update(
                "INSERT INTO portfolio_items (portfolio_id, asset_type, symbol, name, quantity, " +
                "purchase_price, current_price, purchase_date, created_at, updated_at) " +
                "VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)",
                portfolioId, assetType.name(), symbol, name,
                new BigDecimal(quantity), new BigDecimal(purchasePrice),
                new BigDecimal(currentPrice),
                Timestamp.valueOf(purchaseDate),
                Timestamp.valueOf(purchaseDate),
                Timestamp.valueOf(purchaseDate));
    }

    private Portfolio buildPortfolio(Long id, Long userId, Long portfolioNumber, String name,
                                      String description, String currency,
                                      RiskLevel riskLevel, InvestmentGoal investmentGoal,
                                      BigDecimal targetValue, InvestmentHorizon investmentHorizon) {
        Portfolio p = new Portfolio();
        p.setId(id);
        p.setUserId(userId);
        p.setPortfolioNumber(portfolioNumber);
        p.setName(name);
        p.setDescription(description);
        p.setCurrency(currency);
        p.setRiskLevel(riskLevel);
        p.setInvestmentGoal(investmentGoal);
        p.setTargetValue(targetValue);
        p.setInvestmentHorizon(investmentHorizon);
        return p;
    }
