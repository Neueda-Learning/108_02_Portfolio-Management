    @Test
    void findAll_returnsAllPortfolios_withItemsLoaded() {
        insertPortfolio(10L, 1L, 1L, "Growth", null, "USD",
                RiskLevel.AGGRESSIVE, InvestmentGoal.GROWTH, new BigDecimal("100000.0000"),
                InvestmentHorizon.LONG_TERM,
                LocalDateTime.of(2026, 1, 1, 0, 0),
                LocalDateTime.of(2026, 1, 2, 0, 0));
        insertPortfolio(20L, 2L, 1L, "Income", "Safe income", "EUR",
                RiskLevel.CONSERVATIVE, InvestmentGoal.INCOME, null,
                InvestmentHorizon.SHORT_TERM,
                LocalDateTime.of(2026, 2, 1, 0, 0),
                LocalDateTime.of(2026, 2, 2, 0, 0));
        insertPortfolioItem(10L, AssetType.STOCK, "AAPL", "Apple",
                "1.0000", "150.00", "170.00",
                LocalDateTime.of(2026, 1, 10, 9, 0));

        List<Portfolio> all = repository.findAll();

        assertEquals(2, all.size());
        Portfolio growth = all.stream().filter(p -> p.getId() == 10L).findFirst().orElseThrow();
        assertAll(
                () -> assertEquals(1L, growth.getUserId()),
                () -> assertEquals("Growth", growth.getName()),
                () -> assertEquals(RiskLevel.AGGRESSIVE, growth.getRiskLevel()),
                () -> assertEquals(InvestmentGoal.GROWTH, growth.getInvestmentGoal()),
                () -> assertEquals(InvestmentHorizon.LONG_TERM, growth.getInvestmentHorizon()),
                () -> assertEquals(new BigDecimal("100000.0000"), growth.getTargetValue()),
                () -> assertEquals("USD", growth.getCurrency()),
                () -> assertEquals(1, growth.getItems().size()),
                () -> assertEquals("AAPL", growth.getItems().get(0).getSymbol())
        );
    }

