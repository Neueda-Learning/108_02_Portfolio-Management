        insertPortfolioItem(10L, AssetType.STOCK, "AAPL", "Apple", "1.0000", "150.00", "170.00", LocalDateTime.of(2026, 2, 1, 9, 0));
        insertPortfolioItem(20L, AssetType.STOCK, "GOOG", "Google", "2.0000", "100.00", "110.00", LocalDateTime.of(2026, 2, 1, 9, 0));

        List<Portfolio> portfolios = repository.findByUserId(1L);

        Portfolio p1 = portfolios.stream().filter(p -> p.getName().equals("P1")).findFirst().orElseThrow();
