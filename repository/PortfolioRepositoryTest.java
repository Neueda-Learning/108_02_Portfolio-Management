    // ── save – update ────────────────────────────────────────────────────────────

    @Test
    void save_updatesExistingPortfolio_refreshesUpdatedAtAndPersistsAllChanges() {
        LocalDateTime oldUpdatedAt = LocalDateTime.of(2026, 1, 1, 0, 0);
        insertPortfolio(10L, 1L, 1L, "Old", "old desc", "USD",
                RiskLevel.CONSERVATIVE, InvestmentGoal.INCOME,
                new BigDecimal("10000.0000"), InvestmentHorizon.SHORT_TERM,
                LocalDateTime.of(2026, 1, 1, 0, 0), oldUpdatedAt);

        Portfolio existing = repository.findById(10L).orElseThrow();
        existing.setName("Updated");
        existing.setDescription("new desc");
        existing.setCurrency("EUR");
        existing.setRiskLevel(RiskLevel.AGGRESSIVE);
        existing.setInvestmentGoal(InvestmentGoal.GROWTH);
        existing.setTargetValue(new BigDecimal("99999.0000"));
        existing.setInvestmentHorizon(InvestmentHorizon.LONG_TERM);

        Portfolio updated = repository.save(existing);

        assertNotNull(updated.getUpdatedAt());
        assertTrue(updated.getUpdatedAt().isAfter(oldUpdatedAt));

        Portfolio persisted = repository.findById(10L).orElseThrow();
        assertAll(
                () -> assertEquals("Updated",             persisted.getName()),
                () -> assertEquals("new desc",            persisted.getDescription()),
                () -> assertEquals("EUR",                 persisted.getCurrency()),
                () -> assertEquals(RiskLevel.AGGRESSIVE,  persisted.getRiskLevel()),
                () -> assertEquals(InvestmentGoal.GROWTH, persisted.getInvestmentGoal()),
                () -> assertEquals(InvestmentHorizon.LONG_TERM, persisted.getInvestmentHorizon()),
                () -> assertEquals(new BigDecimal("99999.0000"), persisted.getTargetValue())
        );
    }

