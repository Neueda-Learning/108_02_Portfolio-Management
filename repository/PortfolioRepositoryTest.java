    @BeforeEach
    void setUpSchema() {
        jdbcTemplate.execute("DROP ALL OBJECTS");
        jdbcTemplate.execute("""
                CREATE TABLE users (
                    user_id BIGINT PRIMARY KEY,
                    username VARCHAR(255) NOT NULL,
                    wallet_balance DECIMAL(19, 2) NOT NULL
                )
                """);
        jdbcTemplate.execute("""
                CREATE TABLE portfolios (
                    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id    BIGINT NOT NULL,
                    portfolio_number BIGINT NOT NULL,
                    name       VARCHAR(255) NOT NULL,
                    description VARCHAR(1000),
                    currency   VARCHAR(10),
                    risk_level  VARCHAR(50),
                    investment_goal VARCHAR(50),
                    target_value DECIMAL(19, 4),
                    investment_horizon VARCHAR(50),
                    created_at TIMESTAMP NOT NULL,
                    updated_at TIMESTAMP,
                    FOREIGN KEY (user_id) REFERENCES users(user_id)
                )
                """);
        jdbcTemplate.execute("""
                CREATE TABLE portfolio_items (
                    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    portfolio_id   BIGINT NOT NULL,
                    asset_type     VARCHAR(50) NOT NULL,
                    symbol         VARCHAR(255) NOT NULL,
                    name           VARCHAR(255) NOT NULL,
                    quantity       DECIMAL(19, 4) NOT NULL,
                    purchase_price DECIMAL(19, 2) NOT NULL,
                    current_price  DECIMAL(19, 2),
                    purchase_date  TIMESTAMP NOT NULL,
                    created_at     TIMESTAMP,
                    updated_at     TIMESTAMP,
                    notes          VARCHAR(1000),
                    FOREIGN KEY (portfolio_id) REFERENCES portfolios(id)
                )
                """);

        insertUser(1L, "alice", "5000.00");
        insertUser(2L, "bob",   "2000.00");
    }

